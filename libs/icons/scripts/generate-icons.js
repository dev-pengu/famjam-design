import { globSync, mkdirSync, rmSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from '@svgr/core';
import prettier from 'prettier';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS_DIR = path.join(ROOT, 'assets');
const SRC_DIR = path.join(ROOT, 'src');
const OUTPUT_DIR = path.join(SRC_DIR, 'icons');
const WEB_REGISTRY_FILE = path.join(SRC_DIR, 'registry.web.ts');
const NATIVE_REGISTRY_FILE = path.join(SRC_DIR, 'registry.native.ts');

rmSync(OUTPUT_DIR, { recursive: true, force: true });
mkdirSync(OUTPUT_DIR, { recursive: true });
rmSync(WEB_REGISTRY_FILE, { force: true });
rmSync(NATIVE_REGISTRY_FILE, { force: true });

function withBanner(content) {
  return `// Generated by scripts/generate-icons.js
// DO NOT EDIT THIS FILE DIRECTLY
     
${content}`;
}

function toPascalCase(value) {
  return value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

function removeAttribute(source, attributePattern) {
  return source
    .replace(new RegExp(`^[ \t]*${attributePattern}[ \t]*\r?\n`, 'gim'), '')
    .replace(new RegExp(`[ \t]+${attributePattern}`, 'gi'), '');
}

function stripFillAttributes(source) {
  const defsIndex = source.search(/<defs|<Defs/);
  const fillAttrRegex = String.raw`fill=(['"])[^'"]*\1`;

  if (defsIndex === -1) {
    return removeAttribute(source, fillAttrRegex);
  }

  const beforeDefs = removeAttribute(source.slice(0, defsIndex), fillAttrRegex);
  const defsAndAfter = source.slice(defsIndex);

  return `${beforeDefs}${defsAndAfter}`;
}

function normalizeNativePropsType(source) {
  return removeAttribute(source, String.raw`xmlns=(['"])http:\/\/www\.w3\.org\/2000\/svg\1`);
}

function transformSVG(source, componentName, native) {
  return transform(
    source,
    {
      native,
      typescript: true,
      jsxRuntime: 'automatic',
      expandProps: 'end',
      icon: true,
      plugins: ['@svgr/plugin-svgo', '@svgr/plugin-jsx'],
    },
    { componentName },
  );
}

async function writeFormattedFile(filePath, content) {
  const prettierConfig = (await prettier.resolveConfig(filePath, { editorconfig: true })) ?? {};
  const formattedContent = await prettier.format(content, {
    ...prettierConfig,
    filepath: filePath,
  });

  writeFileSync(filePath, formattedContent, 'utf8');
}

async function writeComponentFile(componentName, platform, code) {
  const fileName = `${componentName}.${platform}.tsx`;
  const filePath = path.join(OUTPUT_DIR, fileName);
  await writeFormattedFile(filePath, withBanner(code));
}

const svgFiles = globSync(path.join(ASSETS_DIR, '*.svg')).sort();
const iconEntries = [];

for (const file of svgFiles) {
  const iconName = path.basename(file, '.svg');
  const componentName = toPascalCase(iconName);
  const svgSource = readFileSync(file, 'utf8');

  iconEntries.push({ iconName, componentName });

  const webCode = await transformSVG(svgSource, componentName, false);
  const nativeCode = await transformSVG(svgSource, componentName, true);

  await writeComponentFile(componentName, 'web', stripFillAttributes(webCode));
  await writeComponentFile(componentName, 'native', normalizeNativePropsType(stripFillAttributes(nativeCode)));
}

const enumEntries =
  iconEntries.map(({ iconName }) => ` ${toPascalCase(iconName)} = '${iconName}',`).join('\n') ||
  '  Placeholder = "placeholder",';
const iconTypesTs = withBanner(`export enum IconName {\n${enumEntries}\n}\n`);

await writeFormattedFile(path.join(SRC_DIR, 'icon.types.ts'), iconTypesTs);

async function writeIndexFile(platform) {
  const imports = iconEntries
    .map(({ componentName }) => `import ${componentName} from './icons/${componentName}.${platform}';`)
    .join('\n');

  const iconObjectEntries = iconEntries
    .map(({ iconName, componentName }) => `  '${iconName}': ${componentName},`)
    .join('\n');

  const indexContent = withBanner(
    `${imports}\n\nexport const icons = {\n${iconObjectEntries}\n};\n\nexport { IconName } from './icon.types';\n`,
  );

  const indexFilePath = path.join(SRC_DIR, `index.${platform}.ts`);
  await writeFormattedFile(indexFilePath, indexContent);
}

await writeIndexFile('web');
await writeIndexFile('native');

console.log(`Generated ${svgFiles.length} web/native icon component pairs in src/icons`);
console.log('Generated icon.types.ts in src');
console.log('Generated index.web/native TS files in src');
